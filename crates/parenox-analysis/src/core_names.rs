//! Recognized function-valued Vars in the standard clojure.core namespace.

pub(crate) fn known_core_function(name: &str) -> bool {
    matches!(
        name,
        "*" | "+"
            | "-"
            | "/"
            | "<"
            | "<="
            | "="
            | "=="
            | ">"
            | ">="
            | "apply"
            | "assoc"
            | "assoc-in"
            | "boolean"
            | "boolean?"
            | "byte"
            | "char"
            | "char?"
            | "conj"
            | "cons"
            | "contains?"
            | "count"
            | "dec"
            | "deref"
            | "dissoc"
            | "double"
            | "empty?"
            | "every?"
            | "ex-data"
            | "ex-info"
            | "filter"
            | "filterv"
            | "first"
            | "float"
            | "fnil"
            | "get"
            | "get-in"
            | "group-by"
            | "hash-map"
            | "identity"
            | "inc"
            | "int"
            | "int?"
            | "integer?"
            | "into"
            | "key"
            | "keys"
            | "keyword?"
            | "last"
            | "list"
            | "long"
            | "map"
            | "map?"
            | "mapcat"
            | "mapv"
            | "merge"
            | "merge-with"
            | "next"
            | "nil?"
            | "not"
            | "nth"
            | "number?"
            | "partial"
            | "pos?"
            | "prn"
            | "println"
            | "re-find"
            | "re-matches"
            | "reduce"
            | "reduce-kv"
            | "rest"
            | "seq"
            | "set"
            | "set?"
            | "short"
            | "some"
            | "some?"
            | "str"
            | "string?"
            | "subs"
            | "symbol?"
            | "update"
            | "update-in"
            | "update-keys"
            | "update-vals"
            | "val"
            | "vals"
            | "vec"
            | "vector"
            | "vector?"
            | "zero?"
    )
}
